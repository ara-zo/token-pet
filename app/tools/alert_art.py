"""Copy the 작업 알림 art from the mockup board into the widget.

Reads a saved copy of the canvas file project/TurnAlertsSpecies.dc.html (7 species x 5 states) and writes
src/alerts-art.js: for each species and state, how far the pet steps aside, whether it faces the other way,
which body motion it plays, and the exact overlay drawn over the pet (furnace, shovel, "?", sparkles),
all in the sprite box's own coordinates. The keyframes come along too.

    python3 tools/alert_art.py path/to/TurnAlertsSpecies.dc.html
"""
import json
import re
import sys
from pathlib import Path

NAMES = {'모찌': 'mochi', '결정 다람쥐': 'squirrel', '두더지': 'mole', '굴뚝 로봇': 'robot',
         '별가루 펭귄': 'penguin', '유리볼 햄스터': 'hamster', '안테나 토끼': 'rabbit'}
STATES = ['idle', 'working', 'waiting', 'done', 'multi']


def block(s, start):
    """The element starting at `start` (a <div>), up to its matching </div>."""
    depth = 0
    for m in re.finditer(r'<div\b|</div>', s[start:]):
        depth += 1 if m.group(0) == '<div' else -1
        if depth == 0:
            return s[start:start + m.end()]
    raise ValueError('unbalanced div')


def first_svg_end(s):
    depth = 0
    for m in re.finditer(r'<svg\b|</svg>', s):
        depth += 1 if m.group(0) == '<svg' else -1
        if depth == 0:
            return m.end()
    raise ValueError('no svg')


def main(path):
    src = Path(path).read_text(encoding='utf-8')
    css = re.search(r'<style>(.*?)</style>', src, re.S).group(1)
    art = {}
    for name, kind in NAMES.items():
        pos = src.index(f'>{name}</span>')
        art[kind] = {}
        for state in STATES:
            a = src.index('<div style="position: relative; width: 180', pos)
            tile = block(src, a)
            pos = a + len(tile)
            fx_at = tile.index('<div style="position: absolute; left: ')
            fx = block(tile, fx_at)
            left = int(re.match(r'<div style="position: absolute; left: (-?\d+)px', fx).group(1))
            inner = fx[fx.index('>') + 1:-len('</div>')]
            cut = first_svg_end(inner)
            sprite, overlay = inner[:cut], inner[cut:]
            cls = re.search(r'<svg class="([^"]*)"', sprite)
            motion = [c for c in (cls.group(1).split() if cls else []) if c in ('pk-bob', 'pk-tilt', 'pk-hop')]
            art[kind][state] = {
                'shift': left - 6,
                'flip': 'matrix(-1 0 0 1 64 0)' in sprite,
                'motion': motion[0] if motion else 'pk-bob',
                'overlay': re.sub(r'\s+', ' ', overlay).strip(),
            }
    # keyframes and the classes the overlays use; the sprite's own motions are mapped in styles.css
    keep = []
    for rule in re.findall(r'(@keyframes [\w-]+\{(?:[^{}]*\{[^}]*\})*\}|\.[\w.-]+(?:,\.[\w.-]+)*\{[^}]*\}|@media[^{]*\{(?:[^{}]*\{[^}]*\})*\})', css):
        if rule.startswith('.pk-bob') or rule.startswith('.pk-tilt') or rule.startswith('.pk-hop') or rule.startswith('.pk-still'):
            continue
        keep.append(rule)
    scoped = []
    for rule in keep:
        if rule.startswith('.'):
            sel, body = rule.split('{', 1)
            rule = ','.join(f'.alert-art {s}' for s in sel.split(',')) + '{' + body
        elif rule.startswith('@media'):
            rule = re.sub(r'\{(\.[^{]*)\{', lambda m: '{' + ','.join(f'.alert-art {s}' for s in m.group(1).split(',')) + '{', rule)
        scoped.append(rule)
    out = Path(__file__).resolve().parent.parent / 'src' / 'alerts-art.js'
    out.write_text(
        '// Generated by tools/alert_art.py from the mockup board "작업 알림 · 종족별 상태". Do not edit by hand:\n'
        '// change the board, save its TurnAlertsSpecies.dc.html, and run the tool again.\n'
        f'export const ART = {json.dumps(art, ensure_ascii=False, indent=1)};\n'
        f'export const ART_CSS = {json.dumps(chr(10).join(scoped), ensure_ascii=False)};\n',
        encoding='utf-8')
    print(f'wrote {out}: {sum(len(v) for v in art.values())} tiles, {len(scoped)} css rules')


if __name__ == '__main__':
    main(sys.argv[1])
